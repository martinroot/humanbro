def разрешённые_роли(режим: str, фокус: str = "") -> set[str]:
    """Какие роли вкладок допустимы в режиме.

    Вкладки портала (:8701) здесь НЕТ. Порт нужен как API — /api/ingest,
    /api/win — но открытая доска в браузере только занимает экран
    (владелец 22.10: «У тебя все равно эдж открывает и в хроме эта
    вкладка. Не понимаю к чему она нужна»).
    """
    if режим == Р_ПОИСК:
        return {"лента"}
    if режим == Р_ОБЩЕНИЕ:
        return {"задание"}
    if режим == Р_ИСПОЛНЕНИЕ:
        return {"задание"}
    if режим == Р_СДАЧА:
        # Вкладки карточки Яндекс.Карт в ОБЩЕМ Chrome быть не должно:
        # владелец (22.10) «нельзя ссылку открывать в Хроме. Заказ
        # выполняется Dolphin профилем». Карточка открывается в профиле
        # Dolphin того аккаунта, который оставляет отзыв. В общем Chrome
        # в режиме сдачи — только страница задания (туда вставляем скрины).
        return {"задание"}
    if режим == Р_ОТКЛИК:
        return {"задание"} if str(фокус).isdigit() else set()
    return set()


def _порт_жив(порт: int) -> bool:
    """Жив ли CDP-порт Chrome."""
    try:
        import urllib.request
        with urllib.request.urlopen(f"http://127.0.0.1:{порт}/json/version", timeout=6):
            return True
    except Exception:
        return False


def _поднять_chrome() -> bool:
    """Поднимает видимый Chrome с CDP на 9222.

    Chrome — дочерний процесс парсеров: когда их убивали, он умирал тоже,
    и вместе с ним останавливались монитор чатов и ленты. Поэтому
    поднимаем его ОТДЕЛЬНЫМ процессом и проверяем порт.
    """
    exe = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
    if not Path(exe).exists():
        return False
    try:
        subprocess.Popen(
            [exe, "--remote-debugging-port=9222",
             r"--user-data-dir=C:\chrome-profile",
             "--start-maximized", "--no-first-run",
             "--no-default-browser-check", "about:blank"],
            creationflags=getattr(subprocess, "DETACHED_PROCESS", 0) | 0x00000008)
    except Exception:
        return False
    for _ in range(20):
        time.sleep(1.0)
        if _порт_жив(9222):
            return True
    return False


