# ── Автомат переходов ─────────────────────────────────────────────────────
def шаг() -> dict:
    """Проверяет условия перехода и переключает режим, если нужно."""
    import sys
    sys.path.insert(0, str(HERE))
    cur = прочитать()
    режим = cur["режим"]
    фокус = cur.get("фокус", "")

    if режим == Р_ПОИСК:
        непрочит = непрочитанные_заказы()
        if непрочит:
            новый = Р_ОБЩЕНИЕ
            фокус = sorted(непрочит)[0]
            применить_режим(новый, фокус)
            return {"переход": f"{режим} -> {новый}", "фокус": фокус,
                    "непрочитанных": len(непрочит)}
        return {"переход": None, "режим": режим}

    if режим == Р_ОБЩЕНИЕ:
        непрочит = непрочитанные_заказы()
        if not непрочит:
            применить_режим(Р_ПОИСК)
            return {"переход": f"{режим} -> {Р_ПОИСК}"}
        if фокус not in непрочит:
            фокус = sorted(непрочит)[0]
            записать(режим, фокус)
        return {"переход": None, "режим": режим, "фокус": фокус,
                "непрочитанных": len(непрочит)}

    if режим == Р_ИСПОЛНЕНИЕ:
        # опубликовано → сдача
        try:
            import order_parts as OP
            части = OP.все_части(фокус) if фокус else []
            if части and all(p["state"] in (OP.Ч_ОПУБЛИКОВАНА, OP.Ч_СДАНА)
                             for p in части):
                применить_режим(Р_СДАЧА, фокус)
                return {"переход": f"{режим} -> {Р_СДАЧА}", "фокус": фокус}
        except Exception:
            pass
        return {"переход": None, "режим": режим, "фокус": фокус}

    if режим == Р_СДАЧА:
        try:
            import order_parts as OP
            части = OP.все_части(фокус) if фокус else []
            if части and all(p["submitted"] for p in части):
                применить_режим(Р_ПОИСК)
                return {"переход": f"{режим} -> {Р_ПОИСК}", "фокус": фокус}
        except Exception:
            pass
        return {"переход": None, "режим": режим, "фокус": фокус}

    return {"переход": None, "режим": режим}


