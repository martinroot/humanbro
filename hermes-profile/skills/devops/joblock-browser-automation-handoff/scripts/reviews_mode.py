def классифицировать(url: str) -> tuple[str, str]:
    """(роль, ключ) по URL вкладки."""
    u = (url or "").strip()
    if not u:
        return ("пусто", "")
    if "127.0.0.1:8701" in u:
        return ("портал", "board")
    if "127.0.0.1:8788" in u:
        # ПЕСОЧНИЦА — бутафория, реальных заказов там нет. Портал не поднят
        # на хосте, вкладка с неё бесполезна и только занимает экран.
        return ("песочница", "sb")
    if "127.0.0.1" in u or "localhost" in u:
        return ("служебная", u[:60])
    if "freelance.ru/task" in u:
        return ("лента", "fr")
    if "profi.ru/backoffice/n.php" in u:
        return ("лента", "pr")
    m = re.search(r"client\.work-zilla\.com/freelancer/(\d+)", u)
    if m:
        return ("задание", m.group(1))
    if "client.work-zilla.com" in u:
        return ("лента", "wz")
    if "kwork.ru" in u:
        return ("лента", "kw")
    if "client.insolvo.com" in u:
        return ("лента", "is")
    if "yandex.ru/maps" in u or "yandex.ru/profile" in u:
        return ("яндекс", u[:60])
    return ("прочее", u[:60])


def вкладки() -> list[dict]:
    try:
        raw = urllib.request.urlopen(CDP, timeout=10).read().decode("utf-8")
        данные = json.loads(raw)
    except Exception:
        return []
    out = []
    for t in данные:
        if t.get("type") != "page":
            continue
        url = t.get("url", "")
        роль, ключ = классифицировать(url)
        out.append({"id": t.get("id"), "url": url, "title": t.get("title") or "",
                    "роль": роль, "ключ": ключ})
    return out


def _закрыть(идентификаторы: list[str]) -> int:
    """Закрывает вкладки по CDP."""
    закрыто = 0
    for идентификатор in идентификаторы:
        try:
            urllib.request.urlopen(
                f"http://127.0.0.1:9222/json/close/{идентификатор}", timeout=5).read()
            закрыто += 1
        except Exception:
            pass
    return закрыто


