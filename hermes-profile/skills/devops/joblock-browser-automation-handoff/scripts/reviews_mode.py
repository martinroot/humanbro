def _открыть_страховку() -> bool:
    """Открывает about:blank, чтобы уборка не оставила Chrome с нулём вкладок.

    Chrome с нулём вкладок закрывается сам — 17.11 так и вышло: в режиме
    отклика закрылись все 7 вкладок, браузер умер, а «страховка» звала
    _открыть_портал(), которая давно ничего не открывает. Вкладка-пустышка
    не мусор: она опора режима, как доска портала раньше.
    """
    return _открыть("about:blank")


def _открыть(url: str) -> bool:
    """Открывает вкладку по URL через CDP.

    Chrome требует МЕТОД PUT для /json/new — на GET отвечает 405. Раньше
    открытие всегда молча не срабатывало, и режим оставался с пустым
    about:blank (владелец 22.10: «остальные вкладки не закрываешь,
    статус не переключаешь»).
    """
    try:
        адрес = f"http://127.0.0.1:9222/json/new?{urllib.parse.quote(url, safe='')}"
        req = urllib.request.Request(адрес, method="PUT", data=b"")
        urllib.request.urlopen(req, timeout=15).read()
        return True
    except Exception:
        return False


def _добить_вкладки(режим: str, фокус: str) -> list[str]:
    """Открывает то, что режиму нужно, но чего не было открыто.

    Раньше режим только ЗАКРЫВАЛ лишнее. В «Исполнении» вкладка задания
    не открывалась вовсе — оставался пустой about:blank, и работать
    было не с чем (владелец 22.10: «остальные вкладки не закрываешь,
    статус не переключаешь»).
    """
    открыто: list[str] = []
    роли = разрешённые_роли(режим, фокус)
    имеющие = {в["роль"] for в in вкладки()}
    # Вкладку портала не открываем: портал нужен как API, а доска
    # в браузере только занимает экран.
    if "задание" in роли and фокус:
        url = f"https://client.work-zilla.com/freelancer/{фокус}"
        if not any(в["ключ"] == фокус for в in вкладки()):
            if _открыть(url):
                открыто.append(f"задание {фокус}")
    # Ленты, которые парсеры НЕ открывают: Profi.ru и Freelance.ru читаются
    # из уже авторизованной вкладки, а respond их закрывает. Вернуть их —
    # задача режима поиска, иначе поиск молча теряет две биржи.
    if режим == Р_ПОИСК:
        for url in ЧЕЛОВЕЧЕСКИЕ_ЛЕНТЫ.values():
            if not any(в["url"].rstrip("/").startswith(url.rstrip("/")) for в in вкладки()):
                if _открыть(url):
                    открыто.append(f"лента {url}")
    return открыто


def закрепить_задание(target: str) -> bool:
    """Добавляет вкладку задания в белый список режима (keep-tabs.json).

    Закладка вкладки: по требованию владельца (22.10) «она вообще не
    должна закрываться, пока мы не выполним заказ» — страница заказа
    горит в Chrome весь цикл: пока Dolphin публикует отзыв, потом туда
    вставляются скрины и сдача.
    """
    if not target:
        return False
    try:
        k = json.loads(ФАЙЛ_ЖИВЫХ.read_text(encoding="utf-8"))
    except Exception:
        k = {}
    паттерны = list(k.get("паттерны") or [])
    шаблон = f"client.work-zilla.com/freelancer/{target}"
    if шаблон not in паттерны:
        паттерны.append(шаблон)
    k["паттерны"] = паттерны
    k["закреплено"] = sorted(set((k.get("закреплено") or []) + [str(target)]))
    k["с"] = time.strftime("%Y-%m-%d %H:%M:%S")
    try:
        DATA.mkdir(parents=True, exist_ok=True)
        ФАЙЛ_ЖИВЫХ.write_text(json.dumps(k, ensure_ascii=False, indent=1), encoding="utf-8")
        return True
    except Exception:
        return False


def применить_режим(режим: str | None = None, фокус: str = "") -> dict:
    """Переключает режим и приводит вкладки/процессы к нужному виду.

    Возвращает: что сделано.
    """
    текущий = прочитать()
    if режим is None:
        режим = текущий["режим"]
    if режим not in РЕЖИМЫ:
        raise ValueError(f"неизвестный режим {режим!r}")
    if режим == Р_ОТКЛИК:
        if not str(фокус).isdigit():
            raise ValueError("режим respond требует числовой Workzilla ID")
        # Publish the pause before stopping processes/cleaning tabs so cycle.py
        # cannot start another search tick during the transition.
        записать(режим, фокус)
        # Пауза активации вкладок — до остановки процессов: коннекторы,
        # которые ещё живы, не должны перехватывать фокус у вкладки заказа.
        _поставить_hold(фокус)
    else:
        # Любой другой режим: вкладки снова можно активировать.
        _снять_hold()

    было = len(вкладки())
    # 1. Закрыть всё, что этому режиму не нужно.
    разрешено = разрешённые_роли(режим, фокус)
    закрыть: list[str] = []
    задания_оставить: set[str] = set()
    if режим == Р_ОБЩЕНИЕ:
        # в режиме общения оставляем чаты только заказов с непрочитанным
        задания_оставить = непрочитанные_заказы()
    elif режим in (Р_ИСПОЛНЕНИЕ, Р_СДАЧА, Р_ОТКЛИК):
        задания_оставить = {фокус} if фокус else set()

    for в in вкладки():
        роль = в["роль"]
        оставить = роль in разрешено
        if роль == "задание":
            оставить = оставить and (в["ключ"] in задания_оставить
                                      or (фокус and в["ключ"] == фокус))
        if роль == "портал":
            # портал-доска нужна всегда, но только ОДНА копия.
            оставить = оставить
        if роль == "яндекс":
            # Карточка Яндекс.Карт в общем Chrome — всегда лишняя: работа
            # идёт в профиле Dolphin. Если она открылась — закрываем.
            оставить = False
        if роль == "прочее" and в["url"] in ("about:blank", "chrome://newtab/"):
            # Пустая вкладка. Chrome не даст закрыть последнюю — вместо
            # этого откроет новую пустую. Оставляем: это не мусор, а
            # страховка от вылета Chrome.
            оставить = True
        if not оставить:
            закрыть.append(в["id"])

    # Дубли портала: доска нужна ОДНА, в любом режиме. Пять копий одной
    # страницы — это ровно то «моргание», из-за которого невозможно было
    # разобраться, что происходит на экране.
    портал_идентификаторы = [в["id"] for в in вкладки() if в["роль"] == "портал"]
    if len(портал_идентификаторы) > 1:
        закрыть.extend(портал_идентификаторы[1:])

    # НИКОГДА не закрываем последнюю вкладку. Chrome с нулём вкладок
    # ЗАКРЫВАЕТСЯ сам — и вместе с ним умирают парсеры и монитор чатов.
    # 23.10: уборка закрыла единственную вкладку → Chrome упал → режим
    # «собрался» (владелец: «Падает хром и режим сбирается! Почему????»).
    #
    # Раньше мы просто не закрывали последнюю — и она залипала на весь
    # сеанс. Правильно: сначала открыть пустую страховку (about:blank),
    # потом закрыть. Тогда вкладок всегда ≥1, Chrome жив, и мусор уходит.
    if закрыть and len(вкладки()) - len(закрыть) <= 0:
        # Chrome с нулём вкладок закрывается сам (17.11: так погибли все 7
        # вкладок и браузер). Открываем about:blank ДО закрытия — иначе
        # закрывать будет нечего, а Chrome умрёт.
        _открыть_страховку()
        time.sleep(1.2)

    закрыто = _закрыть(закрыть) if закрыть else 0
    time.sleep(0.4)

    # 1b. Chrome мёртв (упал вместе с парсерами) — поднимаем сами, не ждём
    # watchdog: пока порт не отвечает, ни парсеры, ни монитор не работают.
    # ВАЖНО: подъём СНАЧАЛА, открытие вкладки ПОТОМ: при мёртвом порту
    # открытие падает молча и после старта Chrome остаётся без вкладок —
    # 23.10 из-за обратного порядка ход убивал Chrome и получал unknown.
    if not _порт_жив(9222):
        _поднять_chrome()
        time.sleep(4.0)

    # 1a. Никогда не оставляем ноль вкладок. Chrome с нулём вкладок
    # ЗАКРЫВАЕТСЯ сам, а вместе с ним умирают парсеры и монитор чатов
    # (22.10: режим закрыл три ленты — Chrome умер, и мы перестали видеть
    # заказчиков). Держим доску портала: это и есть опора режима.
    if not вкладки():
        _открыть_страховку()
        time.sleep(1.2)

    # 1c. Открыть то, что режиму нужно (портал, вкладка задания).
    # ВАЖНО: это делается ПОСЛЕ остановки процессов (шаг 2). Раньше вкладка
    # открывалась до остановки парсеров, и парсер тут же закрывал её своей
    # уборкой — режим «Исполнение» оставался без вкладки задания, а
    # владелец видел «биржи открыты, остальные вкладки не закрываешь»
    # (23.10).
    открыто: list[str] = []

    # 2. Процессы: ленты работают только в режиме «Поиск».
    # ВАЖНО: останавливаем ПЕРЕД уборкой. Раньше уборка шла первой, и парсер
    # успевал открыть ленты ПОСЛЕ неё — в режиме «Исполнение» оставались
    # ленты Workzilla и Insolvo (владелец 23.10: «биржи открыты, остальные
    # вкладки не закрываешь»).
    процессы = _переключить_процессы(режим)
    time.sleep(2.0)

    # 2a. Повторная уборка — после остановки процессов. Теперь никто не
    # откроет лишние вкладки.
    #
    # ВАЖНО: НИКОГДА не закрываем последнюю вкладку — Chrome с нулём
    # вкладок ЗАКРЫВАЕТСЯ сам, и вместе с ним умирают парсеры и монитор
    # чатов. Из-за этого 23.10 Chrome «упал» на пустом экране.
    if режим != Р_ПОИСК:
        сейчас = вкладки()
        лишние = [в["id"] for в in сейчас
                  if в["роль"] not in разрешённые_роли(режим, фокус)]
        if лишние and len(сейчас) > 1:
            закрыто += _закрыть(лишние)
            time.sleep(0.6)

    # 2б. DOLPHIN-ПРОФИЛИ. Владелец (23.10): «ЕСЛИ НЕ СТОИТ РЕЖИМ
    # ИСПОЛНЕНИЕ — ЗАКРЫВАЕМ ВСЕГДА ВСЕ DOLPHIN ПРОФИЛИ».
    # Каждый профиль — это отдельный браузер (~9 процессов, ~200 МБ).
    # В режиме «Исполнение» держим профиль рабочего аккаунта, в остальных
    # закрываем все: ленты и монитор в общем Chrome, Dolphin не нужен.
    try:
        import dolphin_pool as DP
        аккаунт = 0
        if режим in (Р_ИСПОЛНЕНИЕ, Р_СДАЧА) and фокус:
            try:
                import status as ST
                con = ST.подключиться()
                row = con.execute("select account_id from flow where target=?",
                                  (фокус,)).fetchone()
                con.close()
                аккаунт = int(row["account_id"]) if row and row["account_id"] else 0
            except Exception:
                аккаунт = 0
        пул = DP.по_режиму(режим, аккаунт)
        процессы["dolphin"] = пул
        if пул.get("закрыто"):
            print(f"   Dolphin: закрыто профилей {len(пул['закрыто'])} "
                  f"(режим «{режим}»)")
    except Exception as e:
        процессы["dolphin"] = {"ошибка": str(e)[:80]}

    # 2a. Теперь открываем нужные вкладки — процессы уже остановлены.
    открыто = _добить_вкладки(режим, фокус)
    if открыто:
        time.sleep(1.2)
    if режим == Р_ОТКЛИК:
        страницы = вкладки()
        target_pages = [page for page in страницы
                        if page["роль"] == "задание" and page["ключ"] == str(фокус)]
        if target_pages:
            лишние = [page["id"] for page in страницы if page["id"] != target_pages[0]["id"]]
            if лишние:
                закрыто += _закрыть(лишние)
                time.sleep(0.4)
        # Вкладки заказа нет — режим отклика не имеет смысла: не «собрался»,
        # а честно упал, чтобы вызывающий (tg_bot) вернул черновик и сказал
        # владельцу. 17.11 «успех» с нулём вкладок стоил закрытого Chrome.
        if not target_pages:
            raise RuntimeError(
                f"режим отклика: вкладка заказа {фокус} не открылась — Chrome без страницы заказа")

    # 3. Сохранить режим. «с» (начало фазы) сбрасываем ТОЛЬКО при реальной
    #    смене режима: смена фокуса внутри той же фазы время фазы не двигает —
    #    иначе лимит удержания фазы (10 мин) сбрасывался каждым ходом и
    #    эскалация-переход в поиск никогда не срабатывала.
    ДА = time.strftime("%Y-%m-%d %H:%M:%S")
    время_фазы = ДА if текущий.get("режим") != режим else (текущий.get("с") or ДА)
    DATA.mkdir(parents=True, exist_ok=True)
    ФАЙЛ_РЕЖИМА.write_text(json.dumps({
        "режим": режим, "фокус": фокус,
        "с": время_фазы,
        "описание": ОПИСАНИЕ[режим],
    }, ensure_ascii=False, indent=1), encoding="utf-8")

    стало = len(вкладки())
    # 4. Записать, какие вкладки нельзя закрывать в этом режиме.
    живые = записать_живые(режим, фокус)

    # 5. Сообщить владельцу в чат. Без этого режимы были невидимы: он
    # смотрел на экран и не понимал, что происходит (владелец 22.10:
    # «Пуляй тогда сюда в чат сообщения о смене режима! Мне нужно
    # отслеживать статусы»).
    детали = f"Вкладок: {стало} (закрыто {закрыто})"
    if процессы.get("остановлены"):
        детали += f"\nОстановлено: {len(процессы['остановлены'])}"
    if процессы.get("запущено"):
        детали += f"\nЗапущено: {len(процессы['запущено'])}"
    try:
        import notify
        notify.смена_режима(режим, фокус, детали)
    except Exception:
        pass

    return {"режим": режим, "было_вкладок": было, "стало_вкладок": стало,
            "закрыто": закрыто, "процессы": процессы, "живые_вкладки": живые}


# ── Процессы ──────────────────────────────────────────────────────────────
def _bun_процессы() -> list[dict]:
    out = subprocess.run(
        ["powershell", "-NoProfile", "-Command",
         "(Get-CimInstance Win32_Process | Where-Object { $_.Name -eq 'bun.exe' }) | "
         "ForEach-Object { $_.ProcessId.ToString() + '|' + $_.CommandLine }"],
        capture_output=True, text=True, timeout=40).stdout
    строки = []
    for строка in out.splitlines():
        if "|" not in строка:
            continue
        pid, cmd = строка.split("|", 1)
        строки.append({"pid": pid.strip(), "cmd": cmd.strip()})
    return строки


def _убить(pid: str) -> None:
    subprocess.run(["powershell", "-NoProfile", "-Command",
                    f"Stop-Process -Id {pid} -Force -ErrorAction SilentlyContinue"],
                   capture_output=True, timeout=30)


def _переключить_процессы(режим: str) -> dict:
    """В каждом режиме работает ТОЛЬКО текущий этап.

    Владелец (22.10): «4 режима. Все остальное должно останавливаться.
    КРОМЕ ТЕКУЩЕГО ЭТАПА!!!»

      поиск      — только ленты (parser.ts)
      общение    — только монитор чатов (watch-chat.ts)
      исполнение — только целевой заказ (ни лент, ни монитора)
      сдача      — только целевой заказ (ни лент, ни монитора)

    Раньше монитор чатов работал и в «Поиске» — это и давало лишние вкладки
    и мешало видеть, что происходит.
    """
    результат = {"остановлены": [], "запущены": []}
    процессы = _bun_процессы()
    парсеры = [p for p in процессы if "parser.ts" in p["cmd"]]
    мониторы = [p for p in процессы if "watch-chat.ts" in p["cmd"]]
    наблюдатели_заказов = [p for p in процессы if "watch-orders.ts" in p["cmd"]]
    короткие_парсеры = [p for p in процессы if any(marker in p["cmd"] for marker in (
        "wz-demand.ts", "fl-demand.ts", "kwork-demand.ts", "profi-demand.ts",
        "insolvo-demand.ts", "task_status.ts"))]

    if режим == Р_ПОИСК:
        # Ленты + монитор чатов одновременно. Раньше монитор считался
        # этапом «Общение» и в «Поиске» его место «неуместно» — но правило
        # владельца (23.10): «сначала активные задачи, дальше мониторинг
        # переписок, дальше если всё чисто — поиск новых». Переписки —
        # постоянный приоритет: ответ клиента не должен ждать смены режима.
        if not парсеры:
            результат["запущены"].extend(_поднять_парсеры())
        if not мониторы:
            результат["запущены"].extend(_поднять_монитор())
    elif режим == Р_ОБЩЕНИЕ:
        # Только монитор чатов. Ленты стоят.
        for p in парсеры:
            _убить(p["pid"])
            результат["остановлены"].append(p["cmd"][:70])
        if not мониторы:
            результат["запущены"].extend(_поднять_монитор())
    else:
        # Исполнение и сдача: работаем с ОДНИМ заказом. Ни лент, ни
        # монитора — только целевая вкладка.
        for p in парсеры + мониторы + наблюдатели_заказов + короткие_парсеры:
            _убить(p["pid"])
            результат["остановлены"].append(p["cmd"][:70])
    return результат


def _поднять_парсеры() -> list[str]:
    """Поднимает ленты (Workzilla, Kwork, Insolvo) отдельными процессами."""
    поднято = []
    for рынок in ("wz", "kw", "is"):
        лог = open(AUT / f"parser-{рынок}.log", "a", encoding="utf-8")
        subprocess.Popen(
            ["cmd", "/c", f"set PARSER_MARKETS={рынок} && bun parser.ts"],
            cwd=str(AUT), stdout=лог, stderr=subprocess.STDOUT,
            creationflags=0x00000008 | 0x00000200)
        поднято.append(f"parser:{рынок}")
    return поднято


def _поднять_монитор() -> list[str]:
    """Поднимает монитор чатов. Список он берёт из реестра сам."""
    лог = open(AUT / "logs-watch-chats-all.txt", "a", encoding="utf-8")
    subprocess.Popen(
        [BUN, "watch-chat.ts", "--minutes", "300", "--пауза", "4000", "--лимит", "14"],
        cwd=str(AUT), stdout=лог, stderr=subprocess.STDOUT,
        creationflags=0x00000008 | 0x00000200)
    return ["watch-chat"]


