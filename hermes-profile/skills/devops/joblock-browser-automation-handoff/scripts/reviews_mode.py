"""
КОНТРОЛЛЕР РЕЖИМОВ РАБОТЫ.

Владелец (22.10): «Вся система может работать в 3 режимах: Поиск, Общение,
Исполнение, Скрин и сдача. Нужно для каждого режима закрывать все и держать
только нужные выборочные вкладки. Невозможно понять и отдебажить причину,
когда открыто и моргает 30 вкладок непонятных. Все моргает, открывается,
разные функции перебивают друг друга. Я визуально не могу тебе указать на
баг, потому что просто не вижу, что происходит.»

Что делает этот модуль:
  1. Держит ТЕКУЩИЙ РЕЖИМ (файл reviews/data/mode.json).
  2. В каждом режиме разрешает РОВНО те вкладки, которые нужны этому
     режиму, и закрывает все остальные. Никаких 30 вкладок.
  3. Управляет ПРОЦЕССАМИ: в режиме «Поиск» работают ленты, в остальных —
     ленты стоят (иначе они перебивают экран). В режиме «Общение» работает
     монитор чатов, в «Исполнение»/«Сдача» — только целевой заказ.
  4. Двигает конечный автомат по условиям перехода.

РЕЖИМЫ:
  search   — ищем новые заказы: открыты ленты (Workzilla/Kwork/Insolvo)
  chat     — переписка: ленты стоят, открыт чат заказа с непрочитанным
  execute  — исполнение: открыт чат с ТЗ + (в отдельном профиле Dolphin)
  submit   — скрины, доказательства, сдача: чат + карточка на Яндексе

Переходы:
  search -> chat    : нашли ответ заказчика (есть непрочитанные)
  chat   -> execute : данных достаточно (ссылка/текст получены)
  chat   -> search  : непрочитанных больше нет
  execute-> submit  : отзыв опубликован, нужны скрины/сдача
  submit -> search  : задание сдано или снято
"""

