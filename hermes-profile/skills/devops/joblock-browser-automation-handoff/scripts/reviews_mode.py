# ── Непрочитанные сообщения ───────────────────────────────────────────────
def непрочитанные_заказы() -> set[str]:
    """Заказы, где заказчик написал, а мы ещё не ответили.

    Источник — per-id логи монитора: строка «ждём ответа... наших:N чужих:M».
    Если M > N, заказчик написал больше, чем мы.
    """
    import sys
    sys.path.insert(0, str(HERE))
    try:
        import chat_state as CS
    except Exception:
        return set()
    out: set[str] = set()
    for лог in AUT.glob("logs-watch-chat-*-live.txt"):
        m = re.search(r"logs-watch-chat-(\d+)-live", лог.name)
        if not m:
            continue
        target = m.group(1)
        if _неотвечено_по_хронологии(лог):
            out.add(target)
    return out


def _неотвечено_по_хронологии(лог) -> bool:
    """Хронология вместо max-счётчиков: «чужих>наших» врёт, когда заказчик
    прислал серию реплик («Исправьте», «Публикуйте»), а мы ответили ОДНИМ
    сообщением — чужих остаётся больше навсегда, фаза ОБЩЕНИЕ зацикливается.
    Неотвечен = ПОСЛЕДНЕЕ событие чужое: маркер «ОТВЕТ ЗАКАЗЧИКА» в логе
    позже последнего увеличения счётчика «наших»."""
    try:
        строки = лог.read_text(encoding="utf-8", errors="replace").splitlines()
    except Exception:
        return False
    послед_чужой = -1
    послед_наш_рост = -1
    наш_пред = None
    for i, л in enumerate(строки):
        if л.startswith("ОТВЕТ ЗАКАЗЧИКА"):
            послед_чужой = i
        м = re.search(r"наших:(\d+)\s+чужих:(\d+)", л)
        if м:
            н = int(м.group(1))
            if наш_пред is not None and н > наш_пред:
                послед_наш_рост = i
            наш_пред = н
    if послед_чужой <= послед_наш_рост:
        return False
    # закрытые/снятые заказы фазу ОБЩЕНИЕ не тянут — вопрос по ним
    # уже не требует ответа от системы
    try:
        target = re.search(r"logs-watch-chat-(\d+)-live", лог.name).group(1)
        con = sqlite3.connect("file:" + str(HERE / "data" / "registry.db") +
                              "?mode=ro", uri=True, timeout=5)
        row = con.execute(
            "SELECT state FROM flow WHERE target=?", (target,)).fetchone()
        con.close()
        if row and str(row[0]) in ("closed", "submitted"):
            # сдан/закрыт: фазу общения не тянет (владелец: «старые не
            # закрываем» — не держим на них систему; ответ шаг не потеряет)
            return False
    except Exception:
        pass
    return True


